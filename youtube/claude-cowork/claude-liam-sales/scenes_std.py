class Scene_B02_ClaudeLiamSales(Scene):
    """Beat B02 — SHOW: layer stack diagram. Narration: It isn\'t built only for a SaaS sales team with a Salesforce admin — though it ha"""
    def construct(self):
        self.camera.background_color = "#F2F0E9"
