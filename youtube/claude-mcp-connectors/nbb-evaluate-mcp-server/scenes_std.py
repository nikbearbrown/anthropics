class Scene_B01_NbbEvaluateMcp(Scene):
    """Beat B01 — SHOW: concept illustration card. Narration: Server A reads tickets. Server B reads and writes them. The task is a status rep"""
    def construct(self):
        self.camera.background_color = "#FFFFFF"
        font = "EB Garamond"

        if "PROBLEM -- why care":
            act = Text("PROBLEM -- why care", font_size=24, color="#2A1A0E", font=font)
            act.to_edge(UP, buff=0.3)
            self.play(FadeIn(act), run_time=0.3)

        # Spark line — terracotta accent
        spark = Line(LEFT * 0.6, RIGHT * 0.6, color="#C8102E", stroke_width=3)
