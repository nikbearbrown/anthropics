        if "Server B reads and writes them":
            line2 = Text("Server B reads and writes them", font_size=28, color="#2A1A0E", font=font)
            line2.scale(min(1.0, 13.0 / max(0.1, line2.width)))
            line2.shift(DOWN * 0.6)
            self.play(Write(line2), run_time=0.4)

        if "The task is a status report -- read-only":
            line3 = Text("The task is a status report -- read-only", font_size=22, color="#2A1A0E", font=font)
